"""Sender ID corridor classification and resolution for outbound SMS.

An SMS with no ``from`` has no number of its own, so it goes out through
the one carrier named in ``settings.sender_id_sms_carrier``. Whether a
destination accepts a dynamic (unregistered) alphanumeric sender ID is
that carrier's rule, so ``sender_id_corridors.CORRIDORS`` holds one
table per carrier, generated by scripts/sender_id_corridors.py from the
carrier's own per-country documentation. A carrier with no table, or a
region the carrier does not document, requires the org's dedicated number.

Outcomes:

- ``custom_ok`` — a dynamic sender ID reaches the handset as sent.
- ``excluded`` — operators replace the ID with a random code, so the brand
  would not show; a dedicated number is used.
- ``always_number`` — no dynamic sender ID there (US, Canada, ...), only
  on some networks, or only after a registration Hail has not made.
- ``platform_default_only`` — pre-registration required and Hail
  registered the platform default ``HAIL`` (Australia on Twilio).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import phonenumbers
from hailhq.core.sender_id_corridors import CORRIDORS, CorridorOutcome

__all__ = ["CorridorOutcome", "SenderResolution", "resolve_sender"]

PLATFORM_DEFAULT_SENDER_ID = "HAIL"


@dataclass
class SenderResolution:
    kind: Literal["dedicated_number_required", "alphanumeric"]
    sender_id: str | None = None


def _classify(to_e164: str, carrier: str) -> CorridorOutcome:
    try:
        region = phonenumbers.region_code_for_number(phonenumbers.parse(to_e164))
    except phonenumbers.NumberParseException:
        region = None
    # Unknown carrier, unknown region or no carrier data — conservative fallback.
    return CORRIDORS.get(carrier, {}).get(region or "", "always_number")


def resolve_sender(
    to_e164: str, custom_sender_id: str | None, carrier: str = "twilio"
) -> SenderResolution:
    """``carrier`` is the one that sends sender-ID SMS
    (``settings.sender_id_sms_carrier``); its own country rules apply."""
    outcome = _classify(to_e164, carrier)

    if outcome == "always_number" or outcome == "excluded":
        return SenderResolution(kind="dedicated_number_required")

    if outcome == "platform_default_only":
        return SenderResolution(
            kind="alphanumeric", sender_id=PLATFORM_DEFAULT_SENDER_ID
        )

    # custom_ok
    return SenderResolution(
        kind="alphanumeric", sender_id=custom_sender_id or PLATFORM_DEFAULT_SENDER_ID
    )
